export const LESSONS: Lesson[] = RAW.map((lesson, index) => ({
  ...lesson,
  number: index + 1,
}));

export function getLesson(id: string): Lesson | undefined {
  return LESSONS.find((lesson) => lesson.id === id);
}

export function lessonsInWorld(worldId: string): Lesson[] {
  return LESSONS.filter((lesson) => lesson.worldId === worldId);
}

export function nextLessonId(id: string): string | null {
  const index = LESSONS.findIndex((lesson) => lesson.id === id);
  if (index < 0 || index >= LESSONS.length - 1) return null;
  return LESSONS[index + 1].id;
}

export function previousLessonId(id: string): string | null {
  const index = LESSONS.findIndex((lesson) => lesson.id === id);
  if (index <= 0) return null;
  return LESSONS[index - 1].id;
}
